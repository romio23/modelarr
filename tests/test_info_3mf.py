"""Test voor 3MF-metadata (render.info_3mf) met nagebouwde Bambu-, Prusa- en kale 3MF-bestanden. Gebruik: python tests/test_info_3mf.py"""
import json, os, sys, tempfile, zipfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import render

NS = 'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"'
MESH = '<resources><object id="1"><mesh><vertices><vertex x="0" y="0" z="0"/><vertex x="1" y="0" z="0"/><vertex x="0" y="1" z="0"/><vertex x="0" y="0" z="1"/></vertices><triangles><triangle v1="0" v2="1" v3="2"/><triangle v1="0" v2="1" v3="3"/></triangles></mesh></object></resources><build><item objectid="1"/></build>'


def make(path, meta=(), extra=None):
    m = ''.join(f'<metadata name="{k}">{v}</metadata>' for k, v in meta)
    with zipfile.ZipFile(path, 'w') as z:
        z.writestr('3D/3dmodel.model', f'<?xml version="1.0"?><model unit="millimeter" {NS}>{m}{MESH}</model>')
        for n, c in (extra or {}).items():
            z.writestr(n, c)


d, bad = tempfile.mkdtemp(), []
def check(name, got, want):
    ok = all(got.get(k) == v for k, v in want.items())
    print('OK  ' if ok else 'FOUT', name, got if not ok else '')
    if not ok: bad.append(name)

make(f'{d}/bambu.3mf', [('Application', 'BambuStudio-01.08.04.51'), ('Title', 'Pi Rack'), ('Designer', 'jan'), ('Description', 'Rack mount voor Pi'), ('CreationDate', '2024-05-01'), ('License', 'CC BY')],
     {'Metadata/project_settings.config': json.dumps({'printer_model': 'Bambu Lab X1 Carbon', 'layer_height': '0.2', 'nozzle_diameter': ['0.4'], 'filament_type': ['PLA', 'PLA', 'PETG']}),
      'Metadata/slice_info.config': '<config><plate><metadata key="index" value="1"/><metadata key="prediction" value="2547"/><metadata key="weight" value="10.62"/></plate><plate><metadata key="prediction" value="3000"/><metadata key="weight" value="5"/></plate></config>'})
check('Bambu', render.info_3mf(f'{d}/bambu.3mf'), dict(application='BambuStudio-01.08.04.51', title='Pi Rack', designer='jan', license='CC BY', created='2024-05-01',
      printer='Bambu Lab X1 Carbon', layer_height='0.2', nozzle='0.4', filament='PLA, PETG', print_time=5547, filament_g=15.6))
make(f'{d}/prusa.3mf', [('Application', 'PrusaSlicer-2.7.1')], {'Metadata/Slic3r_PE.config': '; generated by PrusaSlicer\n; printer_model = MK4S\n; layer_height = 0.15\n; nozzle_diameter = 0.4,0.4\n; filament_type = PETG;PLA\n'})
check('Prusa', render.info_3mf(f'{d}/prusa.3mf'), dict(application='PrusaSlicer-2.7.1', printer='MK4S', layer_height='0.15', nozzle='0.4', filament='PETG, PLA'))
make(f'{d}/kaal.3mf', [('Title', 'Alleen titel'), ('LicenseTerms', 'MIT'), ('Copyright', ''), ('Onbekend', 'x')])
i = render.info_3mf(f'{d}/kaal.3mf'); check('kaal 3MF (geen slicer-info, lege velden weg)', i, dict(title='Alleen titel', license='MIT')); assert set(i) == {'title', 'license'}, i
make(f'{d}/lang.3mf', [('Description', 'x' * 900)]); assert len(render.info_3mf(f'{d}/lang.3mf')['description']) == 800; print('OK   beschrijving afgekapt op 800 tekens')
make(f'{d}/kapot.3mf', [('Title', 'T')], {'Metadata/project_settings.config': '{niet json', 'Metadata/slice_info.config': '<config><oops'})
check('kapotte config-bestanden worden genegeerd', render.info_3mf(f'{d}/kapot.3mf'), dict(title='T'))
open(f'{d}/geen.3mf', 'w').write('geen zip')
try: render.info_3mf(f'{d}/geen.3mf'); bad.append('geen-zip'); print('FOUT geen zip gaf geen fout')
except zipfile.BadZipFile: print('OK   geen zip -> BadZipFile (app toont "geen geldig 3MF")')
sys.exit(1 if bad else 0)
